-- DDL Biblioteca Solidaria
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo VARCHAR(50) NOT NULL,
    documento VARCHAR(50),
    pessoa_juridica BOOLEAN,
    telefone VARCHAR(50),
    endereco VARCHAR(255),
    matricula VARCHAR(50),
    cargo VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS livro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    autor VARCHAR(255) NOT NULL,
    editora VARCHAR(255),
    isbn VARCHAR(50),
    categoria VARCHAR(50),
    ano_publicacao INT
);

CREATE TABLE IF NOT EXISTS item_acervo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT NOT NULL REFERENCES livro(id),
    status VARCHAR(50) NOT NULL,
    tipo_item VARCHAR(50) NOT NULL,
    codigo_tombo VARCHAR(50),
    estado VARCHAR(50),
    localizacao VARCHAR(255),
    arquivo_url VARCHAR(500),
    formato VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS emprestimo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    item_acervo_id BIGINT NOT NULL REFERENCES item_acervo(id),
    data_emprestimo DATE NOT NULL,
    data_prevista_devolucao DATE NOT NULL,
    data_devolucao DATE,
    renovacoes INT NOT NULL DEFAULT 0,
    status VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS multa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id BIGINT NOT NULL REFERENCES emprestimo(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    valor NUMERIC(10, 2) NOT NULL,
    data_geracao DATE NOT NULL,
    data_pagamento DATE,
    status VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    livro_id BIGINT NOT NULL REFERENCES livro(id),
    data_reserva DATE NOT NULL,
    status VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS doacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id BIGINT NOT NULL REFERENCES usuario(id),
    data_registro DATE NOT NULL,
    status VARCHAR(50) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    titulo VARCHAR(255),
    autor VARCHAR(255),
    isbn VARCHAR(50),
    categoria VARCHAR(50),
    estado VARCHAR(50),
    quantidade INT,
    arquivo_url VARCHAR(500),
    formato VARCHAR(50),
    valor NUMERIC(10, 2),
    meio_pagamento VARCHAR(50),
    comprovante VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS bonificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id BIGINT NOT NULL REFERENCES usuario(id),
    tipo VARCHAR(50) NOT NULL,
    descricao VARCHAR(255),
    data_concessao DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuario(id),
    tipo VARCHAR(50) NOT NULL,
    mensagem TEXT NOT NULL,
    data_envio TIMESTAMP NOT NULL,
    lida BOOLEAN NOT NULL DEFAULT FALSE
);
