CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_usuario VARCHAR(20) NOT NULL CHECK (tipo_usuario IN ('DOADOR', 'USUARIO_SITE', 'FUNCIONARIO')),
    documento VARCHAR(40),
    pessoa_juridica BOOLEAN,
    telefone VARCHAR(40),
    endereco TEXT,
    matricula VARCHAR(40),
    cargo VARCHAR(100),
    CHECK (
        (tipo_usuario = 'DOADOR'
            AND documento IS NOT NULL AND pessoa_juridica IS NOT NULL
            AND telefone IS NULL AND endereco IS NULL AND matricula IS NULL AND cargo IS NULL)
        OR (tipo_usuario = 'USUARIO_SITE'
            AND telefone IS NOT NULL AND endereco IS NOT NULL
            AND documento IS NULL AND pessoa_juridica IS NULL AND matricula IS NULL AND cargo IS NULL)
        OR (tipo_usuario = 'FUNCIONARIO'
            AND matricula IS NOT NULL AND cargo IS NOT NULL
            AND documento IS NULL AND pessoa_juridica IS NULL AND telefone IS NULL AND endereco IS NULL)
    )
);

CREATE TABLE doacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id BIGINT NOT NULL REFERENCES usuarios(id),
    data_registro DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('REGISTRADA', 'EM_AVALIACAO', 'ACEITA', 'RECUSADA')),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('LIVRO_FISICO', 'EBOOK', 'DINHEIRO')),
    titulo VARCHAR(300),
    autor VARCHAR(200),
    isbn VARCHAR(20),
    categoria VARCHAR(20) CHECK (categoria IS NULL OR categoria IN ('DIDATICO', 'INFANTIL', 'OUTRO')),
    estado VARCHAR(20) CHECK (estado IS NULL OR estado IN ('OTIMO', 'BOM', 'ACEITAVEL', 'RUIM')),
    quantidade INTEGER CHECK (quantidade IS NULL OR quantidade > 0),
    arquivo_url TEXT,
    formato VARCHAR(30),
    valor NUMERIC(12, 2) CHECK (valor IS NULL OR valor >= 0),
    meio_pagamento VARCHAR(80),
    comprovante TEXT,
    CHECK (
        (tipo = 'LIVRO_FISICO'
            AND titulo IS NOT NULL AND autor IS NOT NULL AND isbn IS NOT NULL
            AND categoria IS NOT NULL AND estado IS NOT NULL AND quantidade IS NOT NULL
            AND arquivo_url IS NULL AND formato IS NULL AND valor IS NULL
            AND meio_pagamento IS NULL AND comprovante IS NULL)
        OR (tipo = 'EBOOK'
            AND titulo IS NOT NULL AND autor IS NOT NULL
            AND arquivo_url IS NOT NULL AND formato IS NOT NULL
            AND isbn IS NULL AND categoria IS NULL AND estado IS NULL AND quantidade IS NULL
            AND valor IS NULL AND meio_pagamento IS NULL AND comprovante IS NULL)
        OR (tipo = 'DINHEIRO'
            AND valor IS NOT NULL AND meio_pagamento IS NOT NULL
            AND titulo IS NULL AND autor IS NULL AND isbn IS NULL AND categoria IS NULL
            AND estado IS NULL AND quantidade IS NULL AND arquivo_url IS NULL AND formato IS NULL)
    )
);

CREATE TABLE livros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(300) NOT NULL,
    autor VARCHAR(200) NOT NULL,
    editora VARCHAR(200),
    isbn VARCHAR(20),
    categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('DIDATICO', 'INFANTIL', 'OUTRO')),
    ano_publicacao INTEGER NOT NULL
);

CREATE TABLE itens_acervo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT REFERENCES livros(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('EXEMPLAR_FISICO', 'EBOOK')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DISPONIVEL', 'EMPRESTADO', 'RESERVADO', 'INDISPONIVEL')),
    codigo_tombo VARCHAR(80) UNIQUE,
    estado VARCHAR(20) CHECK (estado IS NULL OR estado IN ('OTIMO', 'BOM', 'ACEITAVEL', 'RUIM')),
    localizacao VARCHAR(200),
    arquivo_url TEXT,
    formato VARCHAR(30),
    CHECK (livro_id IS NOT NULL),
    CHECK (
        (tipo = 'EXEMPLAR_FISICO'
            AND codigo_tombo IS NOT NULL AND estado IS NOT NULL AND localizacao IS NOT NULL
            AND arquivo_url IS NULL AND formato IS NULL)
        OR (tipo = 'EBOOK'
            AND codigo_tombo IS NULL AND estado IS NULL AND localizacao IS NULL
            AND arquivo_url IS NOT NULL AND formato IS NOT NULL)
    )
);

CREATE TABLE emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    item_acervo_id BIGINT NOT NULL REFERENCES itens_acervo(id),
    data_emprestimo DATE NOT NULL,
    data_prevista_devolucao DATE NOT NULL,
    data_devolucao DATE,
    renovacoes INTEGER NOT NULL DEFAULT 0 CHECK (renovacoes >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ATIVO', 'ATRASADO', 'DEVOLVIDO'))
);

CREATE UNIQUE INDEX emprestimos_item_em_aberto_idx
    ON emprestimos(item_acervo_id)
    WHERE status IN ('ATIVO', 'ATRASADO');

CREATE TABLE multas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id BIGINT NOT NULL UNIQUE REFERENCES emprestimos(id),
    valor NUMERIC(12, 2) NOT NULL CHECK (valor >= 0),
    data_geracao DATE NOT NULL,
    data_pagamento DATE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE', 'PAGA'))
);

CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    livro_id BIGINT NOT NULL REFERENCES livros(id),
    data_reserva DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ATIVA', 'ATENDIDA', 'CANCELADA'))
);

CREATE TABLE bonificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PREMIO', 'CERTIFICADO', 'SELO', 'PARCERIA')),
    descricao TEXT NOT NULL,
    data_concessao DATE NOT NULL
);

CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('LIVRO_DISPONIVEL', 'VENCIMENTO_PROXIMO', 'DOACAO_ACEITA')),
    mensagem TEXT NOT NULL,
    data_envio TIMESTAMP NOT NULL,
    lida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX doacoes_doador_id_idx ON doacoes(doador_id);
CREATE INDEX emprestimos_usuario_id_idx ON emprestimos(usuario_id);
CREATE INDEX reservas_usuario_livro_status_idx ON reservas(usuario_id, livro_id, status);
CREATE INDEX notificacoes_usuario_data_idx ON notificacoes(usuario_id, data_envio DESC);
